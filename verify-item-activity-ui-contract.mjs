import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
let dialog = '', activityOpened = 0;
const ctx = { LS: {}, window: {}, document: {}, localStorage: { getItem: () => null, setItem() {} } };
for (const name of ['core','domain','ui','charts','screens']) vm.runInNewContext(fs.readFileSync('js/' + name + '.js','utf8'),ctx);
const state = ctx.LS.domain.seed();
state.session = state.users.find(u => u.role === 'KS_LS').user_id;
const item = state.items[0];
state.events = [{event_id:'LOG1',item_id:item.item_id,type:'SUA_THOI_GIAN',at:'2026-09-28T01:00:00Z',by:state.session,reason:'PRIVATE_LOG_SENTINEL'}];
state.outbox = [{outbox_id:'SEND1',item_id:item.item_id,channel:'EMAIL',status:'CHO_XAC_NHAN',recipient_name:'SEND_SENTINEL',recipient:'a@example.com'}];
ctx.LS.replace(state);
ctx.LS.ui.openDialog = (title,body) => { dialog = body; }; ctx.LS.ui.closeDialog = () => {};
ctx.LS.ui.toast = () => {};
ctx.LS.app = { render() {}, showActivity() { activityOpened++; } };
ctx.LS.screens.detail(item.item_id);
assert.doesNotMatch(dialog,/PRIVATE_LOG_SENTINEL|SEND_SENTINEL|class="tl"/, 'Detail must hide logs and delivery rows by default');
assert.match(dialog,/data-act="item-activity"/);
assert.match(dialog,/tin.*chờ|chờ.*xác nhận/i, 'Pending actionable notifications must remain discoverable');
ctx.LS.screens.openActivity(item.item_id);
await Promise.resolve(); await Promise.resolve();
assert.equal(activityOpened,1);
const page = ctx.LS.screens.itemActivity();
assert.match(page,/PRIVATE_LOG_SENTINEL/); assert.match(page,/SEND_SENTINEL/);
assert.match(page,/activity-back/); assert.match(page,/activity-send-preview/);
ctx.LS.screens.resetFilters();
assert.doesNotMatch(ctx.LS.screens.itemActivity(),/PRIVATE_LOG_SENTINEL/);
state.session = state.users.find(u => u.role === 'CAN_BO_LS').user_id;
item.assigned_user_id = 'SOMEONE_ELSE';
ctx.LS.screens.openActivity(item.item_id);
assert.equal(activityOpened,1,'Foreign item must not open an activity page');
console.log('Item activity hidden detail, separate page, delivery actions and session scope OK');
